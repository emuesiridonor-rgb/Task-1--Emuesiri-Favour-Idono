# 6. HELPER FUNCTION:
#    FIND QUANTITY BEFORE A PRODUCT
# ============================================================

def get_quantity(text, product):

    # --------------------------------------------------------
    # Check numerical quantity
    # Examples:
    # 2 donuts
    # 5 meat pie
    # 10 yogurt
    # --------------------------------------------------------

    pattern = r'(\d+)\s*' + re.escape(product)
    match = re.search(pattern, text)

    if match:
        return int(match.group(1))

    # --------------------------------------------------------
    # Check written quantity
    # Examples:
    # two donuts
    # five meat pie
    # three yogurt
    # --------------------------------------------------------

    for word, number in quantity_words.items():

        phrase = word + " " + product

        if phrase in text:
            return number


    # --------------------------------------------------------
    # If no quantity is given, assume 1
    # --------------------------------------------------------

    return 1


