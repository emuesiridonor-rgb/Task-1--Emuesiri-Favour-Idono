# 5. HELPER FUNCTION:
#    CONVERT AMOUNTS SUCH AS 2K, 3000, ₦3,000
# ============================================================

def extract_budget(text):

    text = text.lower().replace(",", "").replace("₦", "").strip()

    # Example: 2k
    match = re.search(r'(\d+(?:\.\d+)?)\s*k', text)

    if match:
        return int(float(match.group(1)) * 1000)

    # Example: 3000
    match = re.search(r'\b\d+\b', text)

    if match:
        return int(match.group())

    # Written amounts
    word_numbers = {
        "one thousand": 1000,
        "two thousand": 2000,
        "three thousand": 3000,
        "four thousand": 4000,
        "five thousand": 5000,
        "six thousand": 6000,
        "seven thousand": 7000,
        "eight thousand": 8000,
        "nine thousand": 9000,
        "ten thousand": 10000
    }

    for phrase, amount in word_numbers.items():
        if phrase in text:
            return amount

    return None


